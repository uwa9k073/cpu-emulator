; ============================================================
; 1-е задание: сумма элементов массива
; Вариант 5: одноадресная + Гарвардская архитектура
; Массив: первый элемент — длина, дальше — знаковые числа
; ============================================================

        LDA     Array          ; A = длина массива
        MOV     R1, A          ; R1 = счётчик (длина)
        MOV     R0, #Array+1   ; R0 = указатель на первый элемент данных
        LDA     #0             ; A = 0 (начало суммы)
        MOV     R2, A          ; R2 = текущая сумма

Loop:   LDA     (R0)           ; A = текущий элемент массива
        ADD     R2             ; A = A + сумма
        MOV     R2, A          ; сохранить новую сумму в R2
        INC     R0             ; указатель на следующий элемент
        DEC     R1             ; уменьшить счётчик
        JNZ     Loop           ; если R1 ≠ 0 — повторить цикл

        ; Сумма сейчас в R2 и в A
        STA     Result         ; сохранить результат в память данных
        HLT                    ; останов процессора

; ============================================================
; Данные (память данных)
; ============================================================
.data
Array:  DW  5, 12, -7, 3, -1, 8     ; длина = 5, затем 5 элементов
Result: DW  0                       ; здесь будет лежать сумма
